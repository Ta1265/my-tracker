#!/usr/bin/env node
// Generates the two committed contract artifacts: backend/openapi.json (from the
// compiled backend, preview mode, no database) and frontend/types/api.d.ts (from that
// spec). Split into --only=spec / --only=types because each half runs in a different
// Docker build context.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const openApiSpecPath = path.join(repoRoot, 'backend', 'openapi.json');
const apiTypesPath = path.join(repoRoot, 'frontend', 'types', 'api.d.ts');
const apiTypesHeader =
  '/**\n' +
  ' * Generated by `pnpm spec:generate` from backend/openapi.json.\n' +
  ' * Do not edit directly.\n' +
  ' */\n\n';

const args = process.argv.slice(2);
const check = args.includes('--check');
const onlyArg = args.find((arg) => arg.startsWith('--only='));
const only = onlyArg ? onlyArg.slice('--only='.length) : 'both';
const runSpec = only === 'both' || only === 'spec';
const runTypes = only === 'both' || only === 'types';

async function generateSpecDocument() {
  const backendMainPath = path.join(repoRoot, 'backend', 'dist', 'main.js');
  if (!fs.existsSync(backendMainPath)) {
    throw new Error(
      'backend/dist is missing - run `pnpm --filter @portfolio/backend build` first',
    );
  }
  // Anchored at backend/dist/main.js so requires (both package names and the relative
  // ./app.module and ./openapi/document imports below) resolve against backend's own
  // node_modules, exactly as the compiled output expects.
  const backendRequire = createRequire(backendMainPath);
  const { NestFactory } = backendRequire('@nestjs/core');
  const { SwaggerModule } = backendRequire('@nestjs/swagger');
  const { AppModule } = backendRequire('./app.module');
  const { GLOBAL_PREFIX, createOpenApiDocumentBuilder } = backendRequire('./openapi/document');

  // Preview mode registers every module and controller but instantiates no providers,
  // so this needs no database and no env vars.
  const app = await NestFactory.create(AppModule, { preview: true, logger: false });
  app.setGlobalPrefix(GLOBAL_PREFIX);
  const document = SwaggerModule.createDocument(app, createOpenApiDocumentBuilder().build());
  await app.close();
  return JSON.stringify(document, null, 2) + '\n';
}

async function runSpecHalf() {
  const generated = await generateSpecDocument();
  if (check) {
    const onDisk = fs.existsSync(openApiSpecPath) ? fs.readFileSync(openApiSpecPath, 'utf8') : null;
    if (onDisk !== generated) {
      console.error(
        'backend/openapi.json is stale - run `pnpm spec:generate` and commit the result',
      );
      process.exitCode = 1;
      return;
    }
    console.log('backend/openapi.json is up to date');
    return;
  }
  fs.writeFileSync(openApiSpecPath, generated);
  console.log(`wrote ${path.relative(repoRoot, openApiSpecPath)}`);
}

async function generateTypesDeclaration() {
  // Node API only, reading backend/openapi.json off disk - no backend/dist and no
  // backend/ import, so this half also runs inside the frontend image, which has no
  // backend tree at all.
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(new URL(`file://${openApiSpecPath}`));
  return apiTypesHeader + astToString(ast);
}

async function runTypesHalf() {
  if (!fs.existsSync(openApiSpecPath)) {
    throw new Error(
      'backend/openapi.json is missing - run `pnpm spec:generate` (or the --only=spec half) first',
    );
  }
  const generated = await generateTypesDeclaration();
  if (check) {
    const onDisk = fs.existsSync(apiTypesPath) ? fs.readFileSync(apiTypesPath, 'utf8') : null;
    if (onDisk !== generated) {
      console.error(
        'frontend/types/api.d.ts is stale - run `pnpm spec:generate` and commit the result',
      );
      process.exitCode = 1;
      return;
    }
    console.log('frontend/types/api.d.ts is up to date');
    return;
  }
  fs.writeFileSync(apiTypesPath, generated);
  console.log(`wrote ${path.relative(repoRoot, apiTypesPath)}`);
}

async function main() {
  if (runSpec) {
    await runSpecHalf();
  }
  if (runTypes) {
    await runTypesHalf();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
